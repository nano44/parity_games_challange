#!/usr/bin/env python3
"""Growth fits and plots for the DTL family sweeps (results/fam_*.csv -> results/growth.md, results/plots/*.png).
For each family and pinned solver (dtl-pin, idtl-pin), over sizes where the solver finished with verified strategies:
  - power-law exponent k of y ~ c * n^k (least squares on log y vs log n, the largest 4 sizes with y > 0), for
    y = tangles, iterations, wall seconds; n = number of vertices;
  - the last local exponent (log ratio of the two largest sizes) as a check for an accelerating curve;
  - for wall time also the exponential-fit residual against the power-law residual (which model fits the last 4 better).
Fits are descriptive data, not bounds."""
import os, csv, glob, math, sys
HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
SOLVERS = {"dtl-pin": "#2a78d6", "idtl-pin": "#eb6834"}  # categorical slots 1, 2 (dataviz reference palette)
METRICS = [("tangles", "tangles"), ("iterations", "iterations"), ("wall_s", "wall time (s)")]


def lsq(xs, ys):
    n = len(xs); mx, my = sum(xs) / n, sum(ys) / n
    sxx = sum((x - mx) ** 2 for x in xs)
    if sxx == 0:
        return float("nan"), float("nan")
    k = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sxx
    res = sum((y - my - k * (x - mx)) ** 2 for x, y in zip(xs, ys))
    return k, res


def fits(pts):
    pts = [(n, y) for n, y in pts if y > 0]
    if len(pts) < 3:
        return None
    last = pts[-4:]
    k, rp = lsq([math.log(n) for n, _ in last], [math.log(y) for _, y in last])
    _, re = lsq([n for n, _ in last], [math.log(y) for _, y in last])
    (n1, y1), (n2, y2) = pts[-2], pts[-1]
    kl = math.log(y2 / y1) / math.log(n2 / n1) if n2 != n1 else float("nan")
    return k, kl, rp, re


def main():
    rows_md = ["| family | solver | sizes ok (max n) | status at stop | tangles: k (last) | iterations: k (last) | wall: k (last) | wall: better fit (last 4) |",
               "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    agree = ["| family | sizes | ref uzlk ok | py-zlk ok | dtl/idtl ok (verified) | MISMATCH/BADSTRAT/error |", "| --- | --- | --- | --- | --- | --- |"]
    os.makedirs(os.path.join(RES, "plots"), exist_ok=True)
    try:
        import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
    except ImportError:
        plt = None
    for f in sorted(glob.glob(os.path.join(RES, "fam_*.csv"))):
        fam = os.path.basename(f)[4:-4]
        rows = list(csv.DictReader(open(f)))
        sizes = sorted({int(r["N"]) for r in rows})
        cnt = lambda s, st: sum(1 for r in rows if r["solver"] == s and r["status"] == st)
        badn = sum(1 for r in rows if r["status"] in ("MISMATCH", "BADSTRAT", "error"))
        agree.append(f"| {fam} | {len(sizes)} | {cnt('oink-uzlk', 'ok')} | {cnt('py-zlk', 'ok')} | "
                     f"{cnt('dtl-pin', 'ok')}/{cnt('idtl-pin', 'ok')} | {badn} |")
        data = {}
        for s in SOLVERS:
            ok = sorted(((int(r["n"]), r) for r in rows if r["solver"] == s and r["status"] == "ok"), key=lambda t: t[0])
            data[s] = ok
            last = [r for r in rows if r["solver"] == s][-1]["status"] if any(r["solver"] == s for r in rows) else "-"
            cells = []
            for key, _ in METRICS:
                ft = fits([(n, float(r[key])) for n, r in ok if r[key] not in ("", None)])
                cells.append("-" if not ft else f"{ft[0]:.2f} ({ft[1]:.2f})")
            ft = fits([(n, float(r["wall_s"])) for n, r in ok])
            better = "-" if not ft else ("power" if ft[2] <= ft[3] else "exponential")
            rows_md.append(f"| {fam} | {s} | {len(ok)} ({ok[-1][0] if ok else '-'}) | {last} | {cells[0]} | {cells[1]} | {cells[2]} | {better} |")
        if plt and any(data.values()):
            fig, axs = plt.subplots(1, 3, figsize=(12, 3.4))
            for ax, (key, lab) in zip(axs, METRICS):
                for s, col in SOLVERS.items():
                    pts = [(n, float(r[key])) for n, r in data[s] if r[key] not in ("", None) and float(r[key]) > 0]
                    if pts:
                        ax.plot([p[0] for p in pts], [p[1] for p in pts], color=col, lw=2, marker="o", ms=4, label=s)
                ax.set_xscale("log"); ax.set_yscale("log"); ax.set_xlabel("vertices n"); ax.set_title(lab, fontsize=10, loc="left")
                ax.grid(True, which="major", color="#e4e3df", lw=0.6); ax.spines[["top", "right"]].set_visible(False)
            axs[0].legend(frameon=False, fontsize=8)
            fig.suptitle(f"{fam}: pinned DTL / IDTL (Oink 8fbf0a7), log-log", fontsize=11, x=0.01, ha="left")
            fig.tight_layout(); fig.savefig(os.path.join(RES, "plots", f"{fam}.png"), dpi=110); plt.close(fig)
    with open(os.path.join(RES, "growth.md"), "w") as o:
        o.write("# DTL family sweeps: agreement and fitted growth (generated by fit.py)\n\n")
        o.write("k = least-squares exponent of y ~ n^k over the largest 4 finished sizes; (last) = log-ratio exponent of the two "
                "largest. Descriptive only.\n\n## Agreement\n" + "\n".join(agree) + "\n\n## Growth\n" + "\n".join(rows_md) + "\n")
    print(open(os.path.join(RES, "growth.md")).read())


if __name__ == "__main__":
    main()
