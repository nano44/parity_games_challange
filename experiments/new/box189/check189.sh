#!/bin/bash
# Box 189 REACH check (L-NEW successor 58); run from experiments/new. Prints the lines compared with box189/reach.out.
t=$(mktemp -d)
for gnm in REC_d10_tower_norm RECT_d11_T59_norm KILL_M2D_d6_norm; do
  python3 -I box189/run3.py box189/inst/$gnm.json K,pe,pb,m
  python3 -I box189/run3.py box189/inst/$gnm.json none
done
python3 -I box189/writepg.py box189/inst/REC_d10_tower_norm.json $t/a && cmp -s $t/a_g3.pg box189/inst/REC_d10_tower_mu30_g3.pg && cmp -s $t/a_g3.start box189/inst/REC_d10_tower_mu30_g3.start && cmp -s $t/a_g0.pg box189/inst/REC_d10_tower_mu30_g0.pg && echo "PG REC_d10_tower regenerated byte-identical"
python3 -I box189/writepg.py box189/inst/RECT_d11_T59_norm.json $t/b && cmp -s $t/b_g3.pg box189/inst/RECT_d11_T59_g3.pg && cmp -s $t/b_g3.start box189/inst/RECT_d11_T59_g3.start && cmp -s $t/b_g0.pg box189/inst/RECT_d11_T59_g0.pg && echo "PG RECT_d11_T59 regenerated byte-identical"
rm -rf "$t"
