#!/usr/bin/env python3
"""L-COMP box 45: the README's numbers, computed from out/ (no number typed by hand).
Usage: sum45.py a | b      (env LNEW209 = an archive of claude/l-new 311bbf81, to locate and hash L-NEW's genome files)"""
import sys, os, json, re, glob, hashlib
H = os.path.dirname(os.path.abspath(__file__)); O = os.path.join(H, "out"); L = os.environ.get("LNEW209", "")


def rows(fn):
    R = []
    for l in open(fn):
        if " C 3 " not in l: continue
        z = l.split(" C 3 "); c = json.loads(z[1]); R.append((l.split()[0], int(l.split()[2]), c))
    return R


def locate(b):
    loc = [("experiments/comp/" + d, os.path.join(H, "..", d)) for d in ("box40/inst", "box39/inst", "box41/inst", "box42/inst", "box43/inst", "box45/inst")]
    if L: loc += [("claude/l-new 311bbf81 experiments/new/" + d, os.path.join(L, "experiments/new", d)) for d in
                  ("box202/inst", "box202", "box203/inst", "box204/inst", "box205/inst", "box206/inst", "box207/inst")]
    for lab, d in loc:
        p = os.path.join(d, b)
        if os.path.exists(p): return lab + "/" + b, hashlib.sha1(open(p, "rb").read()).hexdigest()
    return "?", "?"


def part_a():
    sets = [("mine", "deep45_mine.out", "box40/inst ∪ box39/inst ∪ box41/inst"), ("lnew", "deep45_lnew.out", "L-NEW's 25 records + 53 corpus (311bbf81; 76 distinct names)"),
            ("fam", "deep45_fam.out", "box42 CL0/8/16/30, box43 D18_k4/8/16, D10_k16, D80_k16, DHIB26_k0, TMWR4/8/16, TC6G8, TREC, TDHIB26, box45 TRWX"),
            ("big", "deep45_big.out", "box42 CL45, CL90; box43 D10_k32/k64, D18_k32, D80_k32/k64, TMWR32"), ("rand", "deep45_rand.out", "random genomes, rand43.rgen (rand45.py)")]
    print("| set | contents | genome runs | flips | Λ-quiet flips | max depth100 (genome) | deep100 (> 3) | Int100 | max depthNS | deepNS (> 3) | IntNS | max depthMID | unm | pimis |")
    print("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    tot = dict(n=0, fl=0); hi = []
    for nm, fn, what in sets:
        p = os.path.join(O, fn)
        if not os.path.exists(p): print("| %s | %s | not run | | | | | | | | | | | |" % (nm, what)); continue
        R = rows(p)
        if not R: continue
        S = lambda k: sum(c[k] for _, _, c in R); M = lambda k: max(c[k] for _, _, c in R); A = lambda k: max(R, key=lambda r: r[2][k])
        print("| %s | %s | %d | %d | %d | %d (%s) | %d | %d | %d | %d | %d | %d | %d | %d |" % (nm, what, len(R), S("flips"), S("qflip"), M("dmax100"), A("dmax100")[0], S("deep100"), S("Int100"),
              M("dmaxNS"), S("deepNS"), S("IntNS"), M("dmaxMID"), S("unm"), S("pimis")))
        tot["n"] += len(R); tot["fl"] += S("flips")
        for b, nmm, c in R:
            if c["dmaxNS"] >= 2: hi.append((nm, b, nmm, c))
    print("\nTotal over the sets above: %d genome runs, %d flips." % (tot["n"], tot["fl"]))
    one = []
    for nm, fn, what in sets:
        p = os.path.join(O, fn)
        if os.path.exists(p): one += [(nm, b) for b, _, c in rows(p) if c["dmaxNS"] == 1]
    print("\nGenome runs with max depthNS = 1: %d (%s)." % (len(one), "; ".join("%s: %s" % (k, ", ".join(sorted({b for n2, b in one if n2 == k}))) for k in sorted({n2 for n2, _ in one}))))
    print("\nGenomes with max depthNS = 2 (none higher):")
    seen = set()
    for nm, b, nmm, c in hi:
        if (nm == "rand") or b in seen: continue
        seen.add(b); path, sh = locate(b)
        print("- %s (set %s, N + M %d): %s, sha1 %s; depth100 max %d, T3 %d" % (b, nm, nmm, path, sh, c["dmax100"], c["T3"]))
    rh = [x for x in hi if x[0] == "rand"]
    if rh: print("- random set: %d genomes with depthNS 2 (names in out/deep45_rand.out; regenerated by rand45.py from the name)" % len(rh))


def part_b():
    print("| band | seeds (QP at N + M) | best (QP = text-engine qmax, N + M, ratio) | T3 | evals | file |")
    print("| --- | --- | --- | --- | --- | --- |")
    for b in (1, 2, 3):
        lg = open(os.path.join(O, "climb45_B%d.log" % b)).read().splitlines()
        seeds = sorted({re.search(r"seed (\S+) QP (\d+) NM (\d+)", l).groups() for l in lg if l.startswith("START")})
        best = [l for l in lg if l.startswith("BEST") or l.startswith("ALERT")][-1]
        m = re.search(r"BEST (\S+) QP (\d+) NM (\d+) ratio ([\d.]+) \| text engine qmax (\d+) ratio [\d.]+ T3 (\d+)", best)
        ev = re.search(r"evals (\d+)", [l for l in lg if l.startswith("DONE")][-1]).group(1)
        print("| %d | %s | %s, %s, %s | %s | %s | out/climb45/%s |" % (b, "; ".join("%s %s at %s" % s for s in seeds), m.group(5), m.group(3), m.group(4), m.group(6), ev, m.group(1)))
    q = os.path.join(O, "qsec45.out")
    if os.path.exists(q):
        # every best: my qmax (from the climb log BEST line) vs L-RED HOW3 qmax
        mine = {}
        for b in (1, 2, 3):
            for l in open(os.path.join(O, "climb45_B%d.log" % b)):
                m = re.search(r"BEST (\S+) QP (\d+) NM \d+ ratio [\d.]+ \| text engine qmax (\d+) ratio [\d.]+ T3 (\d+)", l)
                if m: mine[m.group(1)] = (int(m.group(3)), int(m.group(4)))
        dm = {}
        for fn in glob.glob(os.path.join(O, "deep45_*.out")):
            for b, nmm, c in rows(fn): dm[b] = (c["qmax"], c["T3"])
        eq = n = 0; fam = []
        for l in open(q):
            b = l.split()[0]; c = json.loads(l.split(None, 3)[3]); ref = mine.get(b) or dm.get(b)
            if ref is None: continue
            n += 1; eq += (ref == (c["qmax"], c["T3"]))
            if not b.startswith("BEST"): fam.append((b, int(l.split()[2]), c["qmax"], c["maxfl"], c["T3"], ref))
        print("\nSecond engine (qsec45.py on L-RED 65's HOW3, out/qsec45.out): (qmax, T3) equal to mine on %d of %d genomes." % (eq, n))
        print("\n| family member | N + M | qmax (HOW3) | max flips of one gate | T3 | mine (qmax, T3) |\n| --- | --- | --- | --- | --- | --- |")
        for f in sorted(fam, key=lambda r: (re.sub(r"\d+", "", r[0]), r[1])): print("| %s | %d | %d | %d | %d | %s |" % f)


if __name__ == "__main__":
    {"a": part_a, "b": part_b}[sys.argv[1]]()
