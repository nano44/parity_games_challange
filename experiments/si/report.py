#!/usr/bin/env python3
"""Tables and log-log plots from out/fam_*.csv (families.py) and out/adv_*.log (adversarial.py).
Writes docs/si/RESULTS.md and docs/si/plots/<family>.png (iterations vs n, log-log, one line per rule; randomized rules:
mean over seeds, with the max as a thin line). Growth fits over the last 3 finished sizes: k = slope of log iters vs log n
(iters ~ n^k), b = geometric mean ratio per +1 in N (iters ~ b^N).  Usage: report.py [csv ...]"""
import sys, os, csv, glob, math, re, collections
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
DOC = os.path.join(ROOT, "docs", "si"); PLOTS = os.path.join(DOC, "plots"); os.makedirs(PLOTS, exist_ok=True)
files = sys.argv[1:] or sorted(glob.glob(os.path.join(HERE, "out", "fam_*.csv")))
rows = []
for f in files:
    if "smoke" in f:
        continue
    rows += list(csv.DictReader(open(f)))
# data[(family, rule)] -> {N: (n, m, [iters per seed], status)}
data = collections.defaultdict(dict)
for r in rows:
    key = (r["family"], r["rule"]); N = int(r["N"])
    d = data[key].setdefault(N, [int(r["n"]), int(r["m"]), [], r["status"], []])
    if r["status"] == "ok":
        d[2].append(int(r["iters"])); d[4].append(float(r["secs"]))
    else:
        d[3] = r["status"]
fams = sorted({k[0] for k in data}, key=lambda f: (f not in ("switchallexp", "switchbestexp"), f))
rules = sorted({k[1] for k in data})


def mean(x):
    return sum(x) / len(x)


def fit(points):
    """points: list of (N, n, iters>0). Returns (k, b) over the last 3."""
    pts = [p for p in points if p[2] > 0][-3:]
    if len(pts) < 2:
        return None, None
    xs = [math.log(p[1]) for p in pts]; ys = [math.log(p[2]) for p in pts]
    mx, my = mean(xs), mean(ys)
    k = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / max(1e-12, sum((x - mx) ** 2 for x in xs))
    b = math.exp((ys[-1] - ys[0]) / (pts[-1][0] - pts[0][0]))
    return k, b


out = ["# L-SI results: iterations per family and rule (generated by experiments/si/report.py)",
       "Cell = iterations (randomized rules: mean over seeds / max); 'timeout' = exceeded the per-run limit; growth fits over the",
       "last 3 finished sizes: k (iters ~ n^k), b (iters ~ b^N per +1 in N). Plots: docs/si/plots/<family>.png (log-log).", ""]
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
for fam in fams:
    Ns = sorted({N for (f, r) in data if f == fam for N in data[(f, r)]})
    frules = [r for r in rules if (fam, r) in data]
    out.append(f"## {fam}")
    out.append("| N | n | m | " + " | ".join(frules) + " |")
    out.append("|---|---|---|" + "---|" * len(frules))
    fig, ax = plt.subplots(figsize=(6, 4))
    for r in frules:
        pts = []
        for N in Ns:
            d = data[(fam, r)].get(N)
            if d and d[2]:
                pts.append((N, d[0], mean(d[2]), max(d[2])))
        if pts:
            ax.plot([p[1] for p in pts], [max(p[2], 0.5) for p in pts], marker="o", label=r)
            if any(p[2] != p[3] for p in pts):
                ax.plot([p[1] for p in pts], [max(p[3], 0.5) for p in pts], linestyle=":", color=ax.lines[-1].get_color())
    for N in Ns:
        n = m = None; cells = []
        for r in frules:
            d = data[(fam, r)].get(N)
            if not d:
                cells.append("-"); continue
            n, m = d[0], d[1]
            if d[2]:
                cells.append(f"{mean(d[2]):.1f} / {max(d[2])}" if len(d[2]) > 1 else str(d[2][0]))
            else:
                cells.append(d[3])
        out.append(f"| {N} | {n} | {m} | " + " | ".join(cells) + " |")
    fits = []
    for r in frules:
        pts = [(N, d[0], mean(d[2])) for N, d in sorted(data[(fam, r)].items()) if d[2]]
        k, b = fit(pts)
        tpts = [(N, d[0], mean(d[4])) for N, d in sorted(data[(fam, r)].items()) if d[4] and mean(d[4]) > 0]
        kt, _ = fit(tpts)
        fits.append((f"{r}: k={k:.2f} b={b:.2f}" if k is not None else f"{r}: -") + (f" time~n^{kt:.2f}" if kt is not None else ""))
    out.append(""); out.append("Growth (last 3 sizes; k: iterations ~ n^k, b per +1 in N, time: wall-clock ~ n^kt, engine-dependent): " + "; ".join(fits)); out.append("")
    ax.set_xscale("log"); ax.set_yscale("log"); ax.set_xlabel("n (vertices)"); ax.set_ylabel("iterations"); ax.set_title(fam)
    ax.legend(fontsize=7); fig.tight_layout(); fig.savefig(os.path.join(PLOTS, f"{fam}.png"), dpi=110); plt.close(fig)
# adversarial logs
adv = collections.defaultdict(list)
for f in sorted(glob.glob(os.path.join(HERE, "out", "adv_*.log"))):
    for line in open(f):
        mt = re.match(r"(\S+) n=(\d+): max iterations ([\d.]+) \(m=(\d+)", line)
        if mt:
            adv[mt.group(1)].append((int(mt.group(2)), float(mt.group(3)), int(mt.group(4))))
if adv:
    out.append("## Adversarial search (hill-climb, n ≤ 10; max iterations found, randomized rules: mean over seeds)")
    ns = sorted({n for v in adv.values() for n, _, _ in v})
    out.append("| rule | " + " | ".join(f"n={n}" for n in ns) + " | fit k (iters ~ n^k, last 4) |")
    out.append("|---|" + "---|" * (len(ns) + 1))
    fig, ax = plt.subplots(figsize=(6, 4))
    for r, v in sorted(adv.items()):
        best = {}
        for n, it, m in v:
            best[n] = max(best.get(n, 0), it)
        pts = sorted(best.items())
        k, _ = fit([(n, n, it) for n, it in pts[-4:]]) if len(pts) >= 2 else (None, None)
        out.append(f"| {r} | " + " | ".join(f"{best[n]:g}" if n in best else "-" for n in ns) + f" | {k:.2f} |" if k is not None else "")
        ax.plot([p[0] for p in pts], [max(p[1], 0.5) for p in pts], marker="o", label=r)
    ax.set_xscale("log"); ax.set_yscale("log"); ax.set_xlabel("n"); ax.set_ylabel("max iterations found"); ax.set_title("adversarial search")
    ax.legend(fontsize=7); fig.tight_layout(); fig.savefig(os.path.join(PLOTS, "adversarial.png"), dpi=110); plt.close(fig)
extra = os.path.join(DOC, "RESULTS-extra.md")
if os.path.exists(extra):
    out.append(open(extra).read())
open(os.path.join(DOC, "RESULTS.md"), "w").write("\n".join(out) + "\n")
print("wrote", os.path.join(DOC, "RESULTS.md"), "and", len(fams), "plots")
