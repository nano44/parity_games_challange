#!/usr/bin/env python3
"""L-LOWER 12: DRUP check of one enc32 (L-COMP read-only copy) fixed-rank prefix UNSAT: builds the CNF (enc32 --cnf), solves it with
pysat Glucose4 with proof, runs l8/sat/drup.c (binary path DRUP), prints CNF sha1, lemma count and drup's verdict, then DELETES the
proof and the CNF (disk trap; the CNF is regenerated by the same command). Usage: drupcheck.py GENOME TARGET PREFIX DRUP WORKDIR"""
import sys, os, subprocess, hashlib
G, C, t, drup, wd = sys.argv[1], sys.argv[2], int(sys.argv[3]), sys.argv[4], sys.argv[5]
here = os.path.dirname(os.path.abspath(__file__)); cnf = os.path.join(wd, f'chk_{os.path.basename(G)}_{os.path.basename(C)}_{t}.cnf')
subprocess.run([sys.executable, os.path.join(here, 'enc32_lcomp.py'), G, C, '8', '--fix', 'ranks', '--prefix', str(t), '--cnf', cnf], check=True, stdout=subprocess.DEVNULL)
sha = hashlib.sha1(open(cnf, 'rb').read()).hexdigest()
from pysat.formula import CNF
from pysat.solvers import Glucose4
F = CNF(from_file=cnf); s = Glucose4(bootstrap_with=F.clauses, with_proof=True); r = s.solve()
if r: print(os.path.basename(G), os.path.basename(C), 'prefix', t, 'SAT (not UNSAT!)'); sys.exit(1)
pf = cnf + '.proof'
with open(pf, 'w') as f: f.writelines(l + '\n' for l in s.get_proof())
out = subprocess.run([drup, cnf, pf], capture_output=True, text=True).stdout.strip().splitlines()[-1]
print(os.path.basename(G), os.path.basename(C), 'prefix', t, 'cnf sha1', sha, 'clauses', len(F.clauses), '| drup:', out)
os.remove(pf); os.remove(cnf)
